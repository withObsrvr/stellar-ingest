package main

import (
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"

	"github.com/withObsrvr/stellar-ingest/internal/parity"
)

// TestParityCompare reads both sides' artifacts and writes the Ticket 04
// comparison.
//
//	PARITY_OUT=/tmp/parity go test -run TestParityCompare .
//
// It fails only on a harness fault — a missing artifact, a canonical form
// mismatch, an unreadable file. A data discrepancy is the output, not a
// failure: this ticket delivers a reviewed report, and a test that went red
// on every difference would have to be disabled to be useful.
func TestParityCompare(t *testing.T) {
	dir := os.Getenv(parityOutEnv)
	if dir == "" {
		t.Skipf("set %s=<dir holding both sides' exports> to build the Ticket 04 comparison", parityOutEnv)
	}

	digests, err := filepath.Glob(filepath.Join(dir, "historical", "*.digest.json"))
	if err != nil || len(digests) == 0 {
		t.Fatalf("no historical digests under %s/historical: %v", dir, err)
	}
	sort.Strings(digests)

	var summary strings.Builder
	summary.WriteString("<!-- generated by `make parity-report`; do not edit by hand -->\n\n")
	summary.WriteString("# Ticket 04 — historical/live Bronze comparison\n\n")
	summary.WriteString(parityReportPreamble)

	for _, hPath := range digests {
		fixture := strings.TrimSuffix(filepath.Base(hPath), ".digest.json")
		lPath := filepath.Join(dir, "live", fixture+".digest.json")

		t.Run(fixture, func(t *testing.T) {
			var h, l parity.Record
			if err := ReadJSON(hPath, &h); err != nil {
				t.Fatalf("read historical digest: %v", err)
			}
			if err := ReadJSON(lPath, &l); err != nil {
				t.Fatalf("read live digest (run the live export with PARITY_DIR=%s): %v", dir, err)
			}

			// Row sets are optional: the digest-level comparison is the
			// credential-free tier meant for CI, and it runs with or without
			// the bulky row artifacts.
			hRows := optionalRowSet(t, filepath.Join(dir, "historical", fixture+".rows.json.gz"))
			lRows := optionalRowSet(t, filepath.Join(dir, "live", fixture+".rows.json.gz"))

			comparison := parity.Compare(&h, &l, hRows, lRows)
			if comparison.FormMismatch != "" {
				t.Fatalf("%s: %s", fixture, comparison.FormMismatch)
			}
			if err := WriteJSON(filepath.Join(dir, "report", fixture+".json"), comparison); err != nil {
				t.Fatalf("write comparison: %v", err)
			}
			summary.WriteString(RenderParityMarkdown(comparison))

			t.Logf("%s: %s", fixture, summarizeVerdicts(comparison))
		})
	}

	reportPath := filepath.Join(dir, "report", "summary.md")
	if err := os.MkdirAll(filepath.Dir(reportPath), 0o755); err != nil {
		t.Fatalf("create report dir: %v", err)
	}
	if err := os.WriteFile(reportPath, []byte(summary.String()), 0o644); err != nil {
		t.Fatalf("write summary: %v", err)
	}
	t.Logf("wrote %s", reportPath)
}

const parityReportPreamble = "" +
	"The verdict column is the harness's mechanical reading of the two sides'\n" +
	"canonical rows. It is **not** the ticket's review vocabulary: only a\n" +
	"reviewer decides whether a difference is provenance-only, an approved\n" +
	"semantic difference, or a bug. `both-empty` in particular is not a pass —\n" +
	"a table with no rows on either side has no columns to compare, so two\n" +
	"entirely different schemas agree there.\n\n"

func optionalRowSet(t *testing.T, path string) *parity.RowSet {
	t.Helper()
	if _, err := os.Stat(path); err != nil {
		return nil
	}
	var rs parity.RowSet
	if err := ReadJSON(path, &rs); err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return &rs
}

func summarizeVerdicts(c parity.FixtureComparison) string {
	counts := map[parity.Verdict]int{}
	for _, tc := range c.Tables {
		counts[tc.Verdict]++
	}
	keys := make([]string, 0, len(counts))
	for v := range counts {
		keys = append(keys, string(v))
	}
	sort.Strings(keys)

	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, k+"="+strconv.Itoa(counts[parity.Verdict(k)]))
	}
	return strings.Join(parts, " ")
}
